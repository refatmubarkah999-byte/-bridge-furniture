export function NavLinks({ items, variant }: { items: NavItem[]; variant: "side" | "bottom" }) {
  const pathname = usePathname();
  const isActive = (item: NavItem) =>
    item.exact ? pathname === item.href : pathname === item.href || pathname.startsWith(`${item.href}/`);

  if (variant === "bottom") {
    const shown = items.slice(0, 5);
    return (
      <ul className="grid" style={{ gridTemplateColumns: `repeat(${shown.length}, minmax(0, 1fr))` }}>
        {shown.map((item) => (
          <li key={item.href}>
            <Link
              href={item.href}
              className={`flex flex-col items-center gap-1 py-2 text-[11px] font-medium ${
                isActive(item) ? "text-walnut-700" : "text-muted"
              }`}
            >
              <Icon d={icons[item.icon]} />
              {item.label}
            </Link>
          </li>
        ))}
      </ul>
    );
  }

  return (
    <ul className="space-y-1">
      {items.map((item) => (
        <li key={item.href}>
          <Link
            href={item.href}
            className={`flex items-center gap-3 rounded-xl px-3 py-2.5 font-medium ${
              isActive(item) ? "bg-walnut-100 text-walnut-900" : "text-muted hover:bg-walnut-50 hover:text-ink"
            }`}
          >
            <Icon d={icons[item.icon]} />
            {item.label}
          </Link>
        </li>
      ))}
    </ul>
  );
}

function Icon({ d }: { d: string }) {
  return (
    <svg viewBox="0 0 24 24" className="h-5 w-5" fill="none" stroke="currentColor" strokeWidth="1.8" strokeLinecap="round" strokeLinejoin="round" aria-hidden="true">
      <path d={d} />
    </svg>
  );
}
